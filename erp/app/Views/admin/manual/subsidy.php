<p>Only for <strong>subsidy</strong> customers: track the government subsidy until the customer receives it.</p>
<ol class="steps">
    <li>Open the project → <strong>Subsidy</strong> card.</li>
    <li>Enter the application no., applied-on date and amount. Update the <strong>Subsidy status</strong> as it moves: Applied on portal → Under verification → Sanctioned → <strong>Received by customer</strong> (or Rejected / Refunded / reversed), with the received-on date. <span class="btnname">Save status</span>.</li>
    <li>When received: <span class="btnname">Close project</span>.</li>
</ol>
<p><span class="path">Reports → Subsidy Status</span> lists every subsidy project with its status and amount.</p>
