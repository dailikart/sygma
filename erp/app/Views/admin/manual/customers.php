<p>Customers come from converted leads, or you can add them directly.</p>
<h4>Add a customer</h4>
<ol class="steps">
    <li><span class="path">Marketing → Customers</span> → <span class="btnname">New Customer</span>.</li>
    <li>Type B2B / B2C, name, phone, address, city, <strong>state</strong> (decides the GST type), GSTIN for B2B, EB service number.</li>
    <li><strong>EB / meter charges paid by</strong>: <em>Company</em> (included in your price) or <em>Customer</em> with the amount collected beyond the invoice (e.g. ₹5,000). This is the default for the customer's invoices.</li>
    <li>Many customers at once (e.g. from your old software)? Use <span class="btnname">Bulk upload</span>: see <a href="<?= site_url('admin/manual/bulk-upload') ?>">Bulk upload</a>.</li>
</ol>
<h4>Customer page</h4>
<p>Shows the customer's invoices, payments, balance due, projects and documents. From here: <span class="btnname">Create Invoice</span>, <span class="btnname">Edit</span>.</p>
<h4>Customer documents (needed for the PCR)</h4>
<ol class="steps">
    <li>Open the invoice or project → <strong>Customer documents</strong>. The checklist comes from <span class="path">Administration → Document Types</span>; required ones are marked.</li>
    <li>Choose the file for each document (Aadhaar, EB bill, property tax…) and upload. Each has <span class="btnname">View</span> / <span class="btnname">Download</span>.</li>
    <li>Something not in the list? Use <span class="btnname">Add other document</span> and type its title.</li>
    <li>Uploaded the wrong file? Click the delete icon <i class="bi bi-trash text-danger"></i> next to it and upload again.</li>
</ol>
<div class="alert alert-warning small mb-0"><i class="bi bi-exclamation-triangle"></i> The <strong>PCR</strong> step in EB / net meter cannot be ticked until every <strong>required</strong> document is uploaded.</div>
