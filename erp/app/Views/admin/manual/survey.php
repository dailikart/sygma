<p>The surveyor visits the site, checks the roof and decides whether the installation can go ahead.</p>
<ol class="steps">
    <li><span class="path">My Tasks</span> → open the project. Use <span class="btnname">Open in Maps</span> to reach the site.</li>
    <li>In the <strong>Site Survey &amp; Approval</strong> card fill: survey date, roof type, shading / obstacles, structure height, cable length, recommended kW, notes.</li>
    <li>Upload <strong>Site / roof photo</strong> and the <strong>Survey sheet</strong> (photos straight from the phone camera are fine).</li>
    <li><span class="btnname">Save progress</span> to save without finishing.</li>
    <li><span class="btnname">Approve site</span>: the store is notified to dispatch material.<br>
        or <span class="btnname">Reject</span> with the reason in Notes: the project goes on hold and the admin is told.</li>
</ol>
<p class="small text-muted">A rejected survey can be reopened later with <span class="btnname">Reopen survey</span>.</p>
