<p>Each project has a private web page for the customer. They open it on their phone, without logging in, and see how their installation is going, so they don't need to call the office to ask.</p>
<h4>What the customer sees</h4>
<ul>
    <li>Their system (kW, type) and project number, with a progress bar ("3 of 6 steps done").</li>
    <li>The step-by-step timeline: survey, dispatch (with delivery dates), installation, DCR, EB / net meter, subsidy. Done steps show the date.</li>
    <li>Payments: invoice total, each receipt, amount paid and balance; bank-loan disbursements.</li>
    <li>Documents still needed for the EB / subsidy application (only the checklist, never the files).</li>
    <li>Subsidy status, AMC cover and service visits.</li>
    <li>After installation: their complaints with status, and a <strong>Report a problem</strong> form that registers a complaint directly (see <a href="<?= site_url('admin/manual/complaints') ?>">Service complaints</a>).</li>
    <li>Call, WhatsApp and email buttons for your office.</li>
</ul>
<p class="small text-muted">Only the customer's first name and city are shown. No phone number, address or document files appear on the page.</p>
<h4>Sharing the link</h4>
<ol class="steps">
    <li>Open the project. The <strong>Customer status page</strong> bar shows the link.</li>
    <li><span class="btnname">Send on WhatsApp</span> opens WhatsApp with a message and the link. Or <span class="btnname">Copy</span> it and paste it anywhere.</li>
    <li>The link is also added automatically to the emails sent when material is dispatched and delivered, installation is completed and the system is commissioned.</li>
    <li>The bar shows when the customer last opened the page.</li>
</ol>
<h4>Sent to the wrong person?</h4>
<p>Click <span class="btnname">Reset link</span> (needs "Projects: assign stages" permission). A new link is made and the old one stops working at once.</p>
