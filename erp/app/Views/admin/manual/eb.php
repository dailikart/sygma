<p>The EB / net-meter process up to commissioning. The commissioning date starts the AMC.</p>
<ol class="steps">
    <li>Open the project → <strong>EB / Net Meter</strong> card. Tick each step with its date as it happens:
        <ul>
            <li>Application acknowledged / feasibility approved</li>
            <li>EB charges paid (<strong>locked until the invoice is fully paid</strong>)</li>
            <li>Sanction received</li>
            <li>PCR (Project Completion Report) uploaded (needs every required customer document)</li>
            <li>EB field inspection done</li>
            <li>Net meter installed &amp; commissioned (grid connected)</li>
        </ul></li>
    <li>Set <strong>EB submission status</strong> to <em>Yes</em> once the application has been submitted to EB (it stays <em>No</em> until then), and fill the EB application no., sanction no. and EB charges.</li>
    <li>Upload the PCR copy, sanction letter, EB charges receipt and commissioning report. <span class="btnname">Save</span> any time.</li>
    <li>Choose the <strong>AMC plan</strong> (starts on the commissioning date).</li>
    <li><span class="btnname">Commissioned – complete EB process</span>. All AMC service visits are scheduled automatically.</li>
</ol>
<div class="alert alert-warning small mb-0"><i class="bi bi-exclamation-triangle"></i> If the screen says the invoice must be fully paid, record the remaining payment (or loan disbursement) first. Pending steps are listed in the message.</div>
